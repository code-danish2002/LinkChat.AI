-- LinkChat Postgres schema (Neon + pgvector).
--
-- Layers:
--   identity   users, guests, login_codes, sessions
--   shared     documents, chunks          one copy per piece of content, whoever added it
--   owned      sources, collections, collection_sources, conversations, messages
--
-- Ownership: owner_id is a plain text id that is either users.id or guests.id.
-- It is deliberately not a foreign key, because it can point at either table.
-- A guest lives 24 hours after its last request; a scheduled job removes
-- expired guests and everything they own.
--
-- Sharing: a document is keyed by content_key (normalised URL, or the hash of
-- an uploaded file). Ten users adding the same URL get ten sources rows that
-- all point at one documents row, so chunks and embeddings exist once.
-- A document is deleted automatically the moment the last source pointing at
-- it is deleted (see trigger at the bottom), and never before.
--
-- Vectors: `embedding` is declared without a fixed dimension because the
-- embedding model is chosen per deployment (384 dims on Render, 768 locally).
-- Retrieval is always scoped to one document or one collection, so a scan over
-- those rows is cheap and no approximate index is needed. documents.embedding_model
-- records which model built the chunks; a mismatch means re-ingest.
--
-- Apply with:  psql "$DATABASE_URL" -f backend/db/schema.postgres.sql
-- Idempotent: safe to run again.

BEGIN;

CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE IF NOT EXISTS meta (
    key   TEXT PRIMARY KEY,
    value TEXT NOT NULL
);
INSERT INTO meta (key, value) VALUES ('schema_version', '1')
    ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value;

-- ---------------------------------------------------------------- identity

CREATE TABLE IF NOT EXISTS users (
    id            TEXT PRIMARY KEY,                       -- usr_...
    email         TEXT NOT NULL UNIQUE,                   -- stored lower-cased
    display_name  TEXT NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_login_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS guests (
    id           TEXT PRIMARY KEY,                        -- gst_..., generated by the browser
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_guests_last_seen ON guests (last_seen_at);

-- One row per "send me a code" request. The code itself is never stored, only
-- its hash. Rows are deleted once consumed or expired.
CREATE TABLE IF NOT EXISTS login_codes (
    id           TEXT PRIMARY KEY,                        -- lgc_...
    email        TEXT NOT NULL,
    display_name TEXT,                                    -- carried from signup until verified
    code_hash    TEXT NOT NULL,
    attempts     INTEGER NOT NULL DEFAULT 0,
    expires_at   TIMESTAMPTZ NOT NULL,
    consumed_at  TIMESTAMPTZ,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_login_codes_email ON login_codes (email, created_at DESC);

-- The browser holds the raw token and sends it as a bearer header; only its
-- hash is stored. expires_at decides the session length (day, week, ...).
CREATE TABLE IF NOT EXISTS sessions (
    id           TEXT PRIMARY KEY,                        -- ses_...
    user_id      TEXT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash   TEXT NOT NULL UNIQUE,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at   TIMESTAMPTZ NOT NULL,
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions (user_id);

-- ---------------------------------------------------------------- shared content

CREATE TABLE IF NOT EXISTS documents (
    id              TEXT PRIMARY KEY,                     -- doc_...
    content_key     TEXT NOT NULL UNIQUE,                 -- normalised URL, or "upload:<sha256>"
    url             TEXT,                                 -- NULL for uploads
    kind            TEXT NOT NULL,                        -- youtube | web | pdf | audio | upload | text ...
    title           TEXT NOT NULL,
    status          TEXT NOT NULL DEFAULT 'pending',      -- pending | processing | ready | failed
    error           TEXT,
    chunk_count     INTEGER NOT NULL DEFAULT 0,
    embedding_model TEXT,                                 -- model that built the chunks
    metadata        JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_documents_status ON documents (status);

CREATE TABLE IF NOT EXISTS chunks (
    id          TEXT PRIMARY KEY,                         -- chk_...
    document_id TEXT NOT NULL REFERENCES documents (id) ON DELETE CASCADE,
    position    INTEGER NOT NULL,                         -- order within the document
    text        TEXT NOT NULL,
    metadata    JSONB NOT NULL DEFAULT '{}'::jsonb,       -- start/end timestamps, page, heading ...
    embedding   vector NOT NULL,
    -- 'simple' config: no language stemming, so it behaves the same for every language
    tsv         tsvector GENERATED ALWAYS AS (to_tsvector('simple', text)) STORED,
    UNIQUE (document_id, position)
);
CREATE INDEX IF NOT EXISTS idx_chunks_document ON chunks (document_id);
CREATE INDEX IF NOT EXISTS idx_chunks_tsv ON chunks USING GIN (tsv);

-- ---------------------------------------------------------------- owned

-- A user's (or guest's) handle on a document. Deleting a source never deletes
-- the document unless this was the last source pointing at it.
CREATE TABLE IF NOT EXISTS sources (
    id          TEXT PRIMARY KEY,                         -- src_...
    owner_id    TEXT NOT NULL,                            -- users.id or guests.id
    document_id TEXT NOT NULL REFERENCES documents (id) ON DELETE CASCADE,
    title       TEXT,                                     -- optional per-owner rename; NULL = document title
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (owner_id, document_id)
);
CREATE INDEX IF NOT EXISTS idx_sources_owner    ON sources (owner_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_sources_document ON sources (document_id);

CREATE TABLE IF NOT EXISTS collections (
    id         TEXT PRIMARY KEY,                          -- col_...
    owner_id   TEXT NOT NULL,
    title      TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_collections_owner ON collections (owner_id, created_at DESC);

CREATE TABLE IF NOT EXISTS collection_sources (
    collection_id TEXT NOT NULL REFERENCES collections (id) ON DELETE CASCADE,
    source_id     TEXT NOT NULL REFERENCES sources (id) ON DELETE CASCADE,
    position      INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (collection_id, source_id)
);

CREATE TABLE IF NOT EXISTS conversations (
    id            TEXT PRIMARY KEY,                       -- cnv_...
    owner_id      TEXT NOT NULL,
    source_id     TEXT REFERENCES sources (id) ON DELETE CASCADE,
    collection_id TEXT REFERENCES collections (id) ON DELETE CASCADE,
    title         TEXT NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK ((source_id IS NOT NULL) <> (collection_id IS NOT NULL))  -- exactly one target
);
CREATE INDEX IF NOT EXISTS idx_conversations_owner      ON conversations (owner_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_conversations_source     ON conversations (source_id, created_at);
CREATE INDEX IF NOT EXISTS idx_conversations_collection ON conversations (collection_id, created_at);

CREATE TABLE IF NOT EXISTS messages (
    id              TEXT PRIMARY KEY,                     -- msg_...
    conversation_id TEXT NOT NULL REFERENCES conversations (id) ON DELETE CASCADE,
    role            TEXT NOT NULL,                        -- user | assistant
    content         TEXT NOT NULL,
    model           TEXT,                                 -- pool member that answered
    mode            TEXT NOT NULL DEFAULT 'qa',
    citations       JSONB NOT NULL DEFAULT '[]'::jsonb,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_messages_conversation ON messages (conversation_id, created_at);

-- ---------------------------------------------------------------- orphan cleanup

-- When the last source pointing at a document goes away, drop the document
-- (and, by cascade, its chunks). Fires for direct deletes, for guest expiry,
-- and for account deletion alike.
CREATE OR REPLACE FUNCTION drop_orphan_document() RETURNS trigger AS $$
BEGIN
    DELETE FROM documents d
     WHERE d.id = OLD.document_id
       AND NOT EXISTS (SELECT 1 FROM sources s WHERE s.document_id = OLD.document_id);
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_sources_drop_orphan ON sources;
CREATE TRIGGER trg_sources_drop_orphan
    AFTER DELETE ON sources
    FOR EACH ROW EXECUTE FUNCTION drop_orphan_document();

COMMIT;
